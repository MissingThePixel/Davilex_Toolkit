def expand(original):
    pe=struct.unpack_from('<I',original,0x3c)[0];opt=pe+24
    count=struct.unpack_from('<H',original,pe+6)[0];table=opt+struct.unpack_from('<H',original,pe+20)[0]
    sections=[struct.unpack_from('<8sIIIIIIHHI',original,table+i*40)for i in range(count)]
    def offset(va):
        for s in sections:
            if s[2]<=va-0x400000<s[2]+s[3]:return s[4]+va-0x400000-s[2]
        raise ValueError('Unmapped Europe vehicle operand')
    if any(s[0].rstrip(b'\0')==b'.dvCars'for s in sections):raise ValueError('Car expansion requires verified source ingredient')
    for address,value in REFERENCES:
        if struct.unpack_from('<I',original,offset(address))[0]!=value:raise ValueError(f'Unexpected Europe vehicle reference {address:#x}')
    if struct.unpack_from('<I',original,offset(0x453c18))[0]!=100:raise ValueError('Unexpected Europe vehicle initializer count')
    sa,fa=struct.unpack_from('<II',original,opt+32);align=lambda n,a:(n+a-1)//a*a
    rva=align(max(struct.unpack_from('<I',original,opt+56)[0],max(s[2]+max(s[1],s[3])for s in sections)),sa)
    raw=align(len(original),fa);size=CAPACITY*STRIDE;stored=align(size,fa);header=table+count*40
    if header+40>min(s[4]for s in sections if s[3])or any(original[header:header+40]):raise ValueError('No free Europe vehicle section header')
    data=bytearray(original);data.extend(bytes(raw+stored-len(data)))
    struct.pack_into('<8sIIIIIIHHI',data,header,b'.dvCars\0',size,rva,stored,raw,0,0,0,0,0xc0000040)
    struct.pack_into('<H',data,pe+6,count+1)
    struct.pack_into('<I',data,opt+8,struct.unpack_from('<I',original,opt+8)[0]+stored)
    struct.pack_into('<I',data,opt+56,align(rva+size,sa));base=0x400000+rva
    for address,value in REFERENCES:
        target=base+CAPACITY*STRIDE if address==0x454ab6 else base+value-OLD
        struct.pack_into('<I',data,offset(address),target)
    struct.pack_into('<I',data,offset(0x453c18),CAPACITY)
    return bytes(data)
